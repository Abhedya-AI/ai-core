"""agent_result.py — Standardized Agent Execution Result DTO."""

from typing import Any

from pydantic import BaseModel, Field


class AgentResult(BaseModel):
    """
    Standardized result model returned by all agent executions.

    Provides a clean, uniform interface for supervisor orchestration,
    metrics aggregation, and user response grounding.
    """

    agent_name: str = Field(..., description="Name of the executing agent")
    success: bool = Field(default=True, description="Whether execution succeeded")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Agent confidence score")
    execution_time_ms: int = Field(default=0, ge=0, description="Execution time in milliseconds")
    evidence: list[str] = Field(default_factory=list, description="Supporting evidence items")
    recommendations: list[str] = Field(default_factory=list, description="Actionable recommendations")
    events: list[dict[str, Any]] = Field(default_factory=list, description="Domain events generated by agent")
    output_data: dict[str, Any] = Field(default_factory=dict, description="Structured agent output payload")
    explanation: str = Field(default="", description="Human-readable explanation summary")
